CREATE TABLE finance_mgmt.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    normalized_name VARCHAR(150) NOT NULL,
    mobile_number VARCHAR(40),
    address VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL
);

CREATE UNIQUE INDEX idx_customers_name_normalized
    ON finance_mgmt.customers (normalized_name);

CREATE TABLE finance_mgmt.cash_flow (
    id BIGINT PRIMARY KEY,
    investment_amount NUMERIC(19, 2) NOT NULL CHECK (investment_amount >= 0),
    financial_balance NUMERIC(19, 2) NOT NULL CHECK (financial_balance >= 0),
    profit_amount NUMERIC(19, 2) NOT NULL CHECK (profit_amount >= 0),
    collection_amount NUMERIC(19, 2) NOT NULL CHECK (collection_amount >= 0)
);

INSERT INTO finance_mgmt.cash_flow
    (id, investment_amount, financial_balance, profit_amount, collection_amount)
VALUES
    (1, 0.00, 0.00, 0.00, 0.00);

CREATE TABLE finance_mgmt.loans (
    id VARCHAR(220) PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES finance_mgmt.customers(id),
    loan_type VARCHAR(30) NOT NULL,
    principal_amount NUMERIC(19, 2) NOT NULL CHECK (principal_amount > 0),
    interest_rate NUMERIC(9, 4) NOT NULL CHECK (interest_rate >= 0),
    repayment_frequency VARCHAR(20) NOT NULL,
    weekly_day VARCHAR(15),
    start_date DATE NOT NULL,
    installment_amount NUMERIC(19, 2) NOT NULL CHECK (installment_amount > 0),
    installment_count INTEGER NOT NULL CHECK (installment_count >= 0),
    next_installment_date DATE NOT NULL
);

CREATE INDEX idx_loans_customer_id
    ON finance_mgmt.loans (customer_id);
CREATE INDEX idx_loans_next_installment_date
    ON finance_mgmt.loans (next_installment_date);

CREATE TABLE finance_mgmt.financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type VARCHAR(40) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL CHECK (amount >= 0),
    transaction_date DATE NOT NULL,
    loan_id VARCHAR(220),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_financial_transactions_loan_id
    ON finance_mgmt.financial_transactions (loan_id);

CREATE TABLE finance_mgmt.cash_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(30) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    transfer_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL
);
